// Offline-capable migration helper built on Prisma's WebAssembly schema engine.
// Usage:
//   node scripts/db.mjs diff <name>   -> writes prisma/migrations/<ts>_<name>/migration.sql (schema vs. existing migrations)
//   node scripts/db.mjs deploy        -> applies pending migrations (records them in _prisma_migrations)
// On machines with normal internet access the standard `npx prisma migrate deploy` works the same way.
import "dotenv/config";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// fileURLToPath keeps Windows paths (C:\...) correct.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = path.join(root, "prisma/schema.prisma");
const migDir = path.join(root, "prisma/migrations");
const schema = fs.readFileSync(schemaPath, "utf8");
const url = process.env.DIRECT_URL ?? process.env.DATABASE_URL;
if (!url) throw new Error("DATABASE_URL is not set");

function migrationList() {
  fs.mkdirSync(migDir, { recursive: true });
  const dirs = fs.readdirSync(migDir).filter((d) => fs.statSync(path.join(migDir, d)).isDirectory()).sort();
  const lockPath = path.join(migDir, "migration_lock.toml");
  return {
    baseDir: migDir,
    lockfile: { path: "migration_lock.toml", content: fs.existsSync(lockPath) ? fs.readFileSync(lockPath, "utf8") : null },
    shadowDbInitScript: "",
    migrationDirectories: dirs.map((d) => ({
      path: d,
      migrationFile: { path: "migration.sql", content: { tag: "ok", value: fs.readFileSync(path.join(migDir, d, "migration.sql"), "utf8") } },
    })),
  };
}

/** The WebAssembly schema engine is only needed for `diff`; `deploy` runs plain SQL through node-postgres. */
async function loadEngine() {
  const { SchemaEngine } = await import("@prisma/schema-engine-wasm");
  const { PrismaPg } = await import("@prisma/adapter-pg");
  const { bindMigrationAwareSqlAdapterFactory } = await import("@prisma/driver-adapter-utils");
  return SchemaEngine.new({ datamodels: [["schema.prisma", schema]] }, () => {}, bindMigrationAwareSqlAdapterFactory(new PrismaPg({ connectionString: url })));
}
const filters = { externalTables: [], externalEnums: [] };
const [cmd, name] = process.argv.slice(2);

if (cmd === "diff") {
  const engine = await loadEngine();
  const list = migrationList();
  const from = list.migrationDirectories.length ? { tag: "migrations", ...list } : { tag: "empty" };
  const r = await engine.diff({ from, to: { tag: "schemaDatamodel", files: [{ path: "schema.prisma", content: schema }] }, script: true, exitCode: null, filters });
  const sql = (r.stdout || "").trim();
  if (!sql || /empty migration/i.test(sql)) { console.log("No schema changes."); process.exit(0); }
  const ts = new Date().toISOString().replace(/\D/g, "").slice(0, 14);
  const dir = path.join(migDir, `${ts}_${name || "migration"}`);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "migration.sql"), sql + "\n");
  const lock = path.join(migDir, "migration_lock.toml");
  if (!fs.existsSync(lock)) fs.writeFileSync(lock, '# Please do not edit this file manually\nprovider = "postgresql"\n');
  console.log("Created", path.relative(root, dir));
} else if (cmd === "deploy") {
  // Applied with node-postgres so PL/pgSQL bodies ($$ ... $$) run intact; recorded in the
  // standard _prisma_migrations table so `prisma migrate deploy` sees the same history.
  const { default: pg } = await import("pg");
  const crypto = await import("node:crypto");
  const client = new pg.Client({ connectionString: url });
  await client.connect();
  await client.query(`CREATE TABLE IF NOT EXISTS "_prisma_migrations" (
    "id" VARCHAR(36) PRIMARY KEY NOT NULL, "checksum" VARCHAR(64) NOT NULL, "finished_at" TIMESTAMPTZ,
    "migration_name" VARCHAR(255) NOT NULL, "logs" TEXT, "rolled_back_at" TIMESTAMPTZ,
    "started_at" TIMESTAMPTZ NOT NULL DEFAULT now(), "applied_steps_count" INTEGER NOT NULL DEFAULT 0)`);
  const done = new Set((await client.query(`SELECT migration_name FROM "_prisma_migrations" WHERE finished_at IS NOT NULL AND rolled_back_at IS NULL`)).rows.map((r) => r.migration_name));
  const applied = [];
  for (const m of migrationList().migrationDirectories) {
    if (done.has(m.path)) continue;
    const sql = m.migrationFile.content.value;
    const checksum = crypto.createHash("sha256").update(sql).digest("hex");
    await client.query("BEGIN");
    try {
      await client.query(sql);
      await client.query(`INSERT INTO "_prisma_migrations" (id, checksum, finished_at, migration_name, applied_steps_count) VALUES ($1, $2, now(), $3, 1)`, [crypto.randomUUID(), checksum, m.path]);
      await client.query("COMMIT");
      applied.push(m.path);
    } catch (e) {
      await client.query("ROLLBACK");
      console.error(`Migration ${m.path} failed:`, e.message);
      process.exit(1);
    }
  }
  await client.end();
  console.log(applied.length ? "Applied: " + applied.join(", ") : "Database is up to date.");
} else {
  console.log("Usage: node scripts/db.mjs diff <name> | deploy");
}
process.exit(0);
